#!/usr/bin/env python3
"""Generate DTO declarations from the deliberately small serde contract subset.

Only named structs and unit/adjacently-tagged newtype enums are accepted. Fail
closed when a DTO uses syntax this generator cannot represent. No Rust build.
"""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
SOURCES = ROOT / "src-tauri/src/work_items"
OUTPUT = ROOT / "src/types/work-items.gen.ts"


def snake(name):
    return re.sub(r"(?<!^)([A-Z])", r"_\1", name).lower()


def camel(name):
    first, *rest = name.split("_")
    return first + "".join(word.title() for word in rest)


def split_type(value):
    depth = 0
    for index, char in enumerate(value):
        depth += (char == "<") - (char == ">")
        if char == "," and depth == 0:
            return value[:index].strip(), value[index + 1:].strip()
    raise ValueError(f"Expected two generic arguments: {value}")


def ts_type(value):
    if value in ("String", "bool", "u32", "f64"):
        return {"String": "string", "bool": "boolean", "u32": "number", "f64": "number"}[value]
    generic = re.fullmatch(r"(Option|Vec|BTreeMap|Box)<(.+)>", value)
    if generic:
        kind, inner = generic.groups()
        if kind == "Box":
            return ts_type(inner)
        if kind == "Option":
            return f"{ts_type(inner)} | null"
        if kind == "Vec":
            return f"Array<{ts_type(inner)}>"
        key, item = split_type(inner)
        assert key == "String", "Only string map keys are supported"
        return f"Record<string, {ts_type(item)}>"
    if re.fullmatch(r"WorkItem\w*", value):
        return value
    raise ValueError(f"Unsupported Rust type: {value}")


def generate():
    declarations = []
    for source in ("model.rs", "protocol.rs"):
        code = (SOURCES / source).read_text()
        code = re.sub(r"//[^\n]*", "", code)
        code = re.sub(r"#\[serde\((.*?)\)\]", lambda m: "#[serde(" + " ".join(m[1].split()).replace(", )", ")") + ")]", code, flags=re.S)
        pattern = r'#\[derive\([^\n]+\)\]\s*#\[serde\(([^\n]+)\)\]\s*pub (struct|enum) (WorkItem\w*) \{([^}]+)\}'
        matches = list(re.finditer(pattern, code))
        assert len(matches) == len(re.findall(r"pub (?:struct|enum) ", code)), "Unsupported declaration"
        for match in matches:
            attrs, kind, name, body = match.groups()
            if kind == "struct":
                assert attrs == 'rename_all = "camelCase", deny_unknown_fields', attrs
                fields = []
                optional = False
                for line in filter(str.strip, body.strip().splitlines()):
                    # `#[serde(default)]` marks a field a producer may omit; TS makes the key optional.
                    if line.strip() == "#[serde(default)]":
                        optional = True
                        continue
                    field = re.fullmatch(r"\s*pub (\w+): (.+),\s*", line)
                    assert field, f"Unsupported field: {line}"
                    key, value = field.groups()
                    assert not optional or value.startswith("Option<"), f"Defaulted field must be an Option: {line}"
                    fields.append(f"\t{camel(key)}{'?' if optional else ''}: {ts_type(value)};")
                    optional = False
                declarations.append(f"export interface {name} {{\n" + "\n".join(fields) + "\n}")
            else:
                tagged = 'tag = "kind", content = "value", ' in attrs
                assert attrs == ('tag = "kind", content = "value", rename_all = "snake_case", deny_unknown_fields' if tagged else 'rename_all = "snake_case"'), attrs
                variants = []
                for line in filter(str.strip, body.strip().splitlines()):
                    variant = re.fullmatch(r"\s*(\w+)(?:\((.+)\))?,\s*", line)
                    assert variant, f"Unsupported variant: {line}"
                    key, value = variant.groups()
                    assert bool(value) == tagged, "Mixed enum shapes are unsupported"
                    variants.append(f'{{ kind: "{snake(key)}"; value: {ts_type(value)} }}' if tagged else f'"{snake(key)}"')
                inline = f"export type {name} = " + " | ".join(variants) + ";"
                # Biome (lineWidth 120) breaks a longer union one variant per line; match it so --check agrees.
                declarations.append(f"export type {name} =\n\t| " + "\n\t| ".join(variants) + ";" if tagged or len(inline) > 120 else inline)
    return "// Generated by scripts/generate-work-item-types.py. Do not edit.\n\n" + "\n\n".join(declarations) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    fixture_output = ROOT / "src/plugins/testing/work-items-demo.gen.ts"
    snapshot = json.loads((SOURCES / "demo.json").read_text())
    fixture = "// Generated from the local-only work_items/demo.json. Do not edit.\nimport type { WorkItemProviderSnapshot } from \"../../types/work-items.gen\";\n// biome-ignore format: preserve canonical JSON fixture formatting\nexport const workItemsDemo = " + json.dumps(snapshot, indent="\t") + " satisfies WorkItemProviderSnapshot;\n"
    if args.check:
        if OUTPUT.read_text() != generated or fixture_output.read_text() != fixture:
            raise SystemExit("Work-item types drift: run python3 scripts/generate-work-item-types.py")
    else:
        OUTPUT.write_text(generated)
        fixture_output.write_text(fixture)
